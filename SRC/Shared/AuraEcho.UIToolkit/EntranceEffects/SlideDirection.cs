namespace AuraEcho.UIToolkit.EntranceEffects
{
    /// <summary>
    /// 滑动入场的来向。表示元素从该方向滑入到最终位置。
    /// </summary>
    public enum SlideDirection
    {
        /// <summary>从下方滑入（向上移动到位）。</summary>
        Up,

        /// <summary>从上方滑入（向下移动到位）。</summary>
        Down,

        /// <summary>从右侧滑入（向左移动到位）。</summary>
        Left,

        /// <summary>从左侧滑入（向右移动到位）。</summary>
        Right
    }
}
